#!/usr/bin/env bash
# Isolated CI only: no existing stacks, credentials, published ports or user data.
set -Eeuo pipefail
app_image="${1:?Usage: smoke-test-managed-cli.sh <app-image> <manager-image>}"
manager_image="${2:?Missing Manager image}"
script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
fixture="$(mktemp -d /tmp/mergeron-cli-fixture.XXXXXX)"
stack="mergeron-cli-fixture-${RANDOM}-${RANDOM}"
app="${stack}-ui"
manager="${stack}-manager"
apparmor_loaded=false
cleanup() {
  if [ "$?" -ne 0 ]; then
    docker logs --tail 30 "$manager" 2>/dev/null || true
    docker logs --tail 30 "$app" 2>/dev/null || true
  fi
  # These exact names were generated by this invocation, never broad patterns.
  docker rm -f "$app" "$manager" >/dev/null 2>&1 || true
  if [ "$apparmor_loaded" = true ]; then sudo apparmor_parser -R "$script_dir/../deployment/config/apparmor-document-isolation-ci"; fi
  # Keep the disposable filesystem as evidence; never remove a host data tree.
  echo "Disposable CLI test state: $fixture"
}
trap cleanup EXIT
apparmor_profile=unconfined
if docker info --format '{{json .SecurityOptions}}' | grep -q apparmor; then
  sudo apparmor_parser -r "$script_dir/../deployment/config/apparmor-document-isolation-ci"
  apparmor_loaded=true
  apparmor_profile=mergeron-document-isolation-ci
fi
mkdir -p "$fixture/home" "$fixture/run" "$fixture/state" "$fixture/workspace"
chmod 755 "$fixture"
# Bind directories are created by the CI runner, not by container root. Take
# ownership before chmod; CAP_CHOWN suffices, CAP_FOWNER must not be added.
docker run --rm --read-only --network none --user 0 --cap-drop ALL --cap-add CHOWN \
  --security-opt no-new-privileges:true \
  --mount "type=bind,src=$fixture,dst=/fixture" --entrypoint /nodejs/bin/node \
  "$manager_image" -e 'const f=require("node:fs");for(const p of ["home","workspace"]){f.chownSync("/fixture/"+p,11002,11002)}f.chownSync("/fixture/run",0,11002);f.chmodSync("/fixture/run",0o750);f.chownSync("/fixture/state",0,0);f.chmodSync("/fixture/state",0o700)'
docker run -d --name "$manager" --read-only --network none --cap-drop ALL \
  --cap-add CHOWN --cap-add DAC_READ_SEARCH --security-opt no-new-privileges:true \
  --tmpfs /tmp:rw,nosuid,nodev,size=8m \
  --mount type=bind,src=/var/run/docker.sock,dst=/var/run/docker.sock,readonly \
  --mount "type=bind,src=$fixture,dst=/host-state" \
  --mount "type=bind,src=$fixture/run,dst=/run/mergeron-manager" \
  --mount "type=bind,src=$fixture/state,dst=/var/lib/mergeron-manager" \
  -e "MERGERON_STACK_PREFIX=$stack" -e MERGERON_STACK_ENVIRONMENT=development \
  -e "MERGERON_STATE_ROOT=$fixture" -e MERGERON_INSTALL_ENABLED=false \
  "$manager_image" >/dev/null
docker run -d --name "$app" --read-only --network none --cap-drop ALL \
  --security-opt no-new-privileges:true \
  --security-opt "seccomp=$script_dir/../deployment/config/seccomp-bwrap.json" \
  --security-opt systempaths=unconfined \
  --security-opt "apparmor=$apparmor_profile" \
  --tmpfs /tmp:rw,nosuid,nodev,size=128m,mode=1777 \
  --tmpfs /app/logs:rw,nosuid,nodev,size=32m,uid=11002,gid=11002 \
  --tmpfs /run/secrets:rw,nosuid,nodev,size=1m,uid=11002,gid=11002 \
  --tmpfs /appdata:rw,nosuid,nodev,size=1m,uid=11002,gid=11002 \
  --mount "type=bind,src=$fixture/home,dst=/home/codex" \
  --mount "type=bind,src=$fixture/workspace,dst=/workspaces" \
  --mount "type=bind,src=$fixture/run,dst=/run/mergeron-manager" \
  --mount "type=bind,src=$script_dir/managed-cli-http-probe.cjs,dst=/ci/managed-cli-http-probe.cjs,readonly" \
  --mount "type=bind,src=$script_dir/managed-cli-ui-probe.cjs,dst=/ci/managed-cli-ui-probe.cjs,readonly" \
  --mount "type=bind,src=$script_dir/cli-dictation-native-probe.cjs,dst=/ci/cli-dictation-native-probe.cjs,readonly" \
  --mount "type=bind,src=$script_dir/smoke-test-git-copy-isolation.py,dst=/ci/smoke-test-git-copy-isolation.py,readonly" \
  --label io.mergeron.managed=true --label "io.mergeron.stack=$stack" \
  --label io.mergeron.component=application \
  -e NODE_ENV=test -e PORT=8172 -e WEBUI_API_KEY=isolated-cli-fixture-only \
  -e MERGERON_PUBLISHED_DOCUMENT_PROTECTION=required -e WORKSPACE_ROOTS=/workspaces,/appdata \
  -e WEBUI_REQUIRE_IDENTITY=false -e WEBUI_DB_PATH=/home/codex/.codex/test.sqlite \
  "$app_image" >/dev/null
wait_for_app() {
  for attempt in $(seq 1 60); do
    if docker exec "$app" node -e 'fetch("http://127.0.0.1:8172/api/status",{headers:{authorization:"Bearer "+process.env.WEBUI_API_KEY}}).then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))' >/dev/null 2>&1; then return; fi
    sleep 2
  done
  docker logs "$app"
  return 1
}
wait_for_app
for attempt in $(seq 1 60); do
  if docker exec "$manager" /nodejs/bin/node src/healthcheck.mjs >/dev/null 2>&1; then break; fi
  if [ "$attempt" -eq 60 ]; then exit 1; fi
  sleep 1
done
docker exec "$app" node /ci/managed-cli-http-probe.cjs
docker exec "$app" node /ci/cli-dictation-native-probe.cjs /home/codex/.codex/webui/cli/releases/0.164.0-mergeron.1/codex
docker restart "$app" >/dev/null
wait_for_app
docker exec "$app" node /ci/managed-cli-http-probe.cjs persisted
docker exec "$app" python3 /ci/smoke-test-git-copy-isolation.py /home/codex/.codex/webui/cli/releases/0.164.0-mergeron.1/codex
docker exec "$app" node /ci/managed-cli-ui-probe.cjs
cp -r "$fixture/workspace/.managed-cli-ui" "$fixture/ui"
docker cp -L "$app:/home/codex/.codex/webui/cli/releases/0.164.0-mergeron.1/codex" "$fixture/codex"
chmod 755 "$fixture/codex"
docker rm -f "$app" "$manager" >/dev/null
if [ "$apparmor_loaded" = true ]; then
  sudo apparmor_parser -R "$script_dir/../deployment/config/apparmor-document-isolation-ci"
  apparmor_loaded=false
fi
# Real Core command/exec: interface enumeration, negative security tests, real
# backend + desktop/mobile captures. No AI account or inference is involved.
bash "$script_dir/smoke-test-document-isolation.sh" "$app_image" "$fixture/codex" --netlink-route
if [ -n "${MERGERON_NETLINK_EVIDENCE:-}" ]; then
  cp "$fixture/ui/desktop.png" "$MERGERON_NETLINK_EVIDENCE/cli-settings-desktop.png"
  cp "$fixture/ui/mobile.png" "$MERGERON_NETLINK_EVIDENCE/cli-settings-mobile.png"
fi
